package main

import (
	"encoding/base64"
	"encoding/hex"
	"fmt"
	"path/filepath"
	"strconv"
	"strings"
)

// LookupOptions controls lookup-table (faithful) generation.
type LookupOptions struct {
	Encoding string // "hex" (default), "base64", or "array"
	Loop     string // "loop" (default), "hold", or "silence"
	Center   int
}

func validateLookupOptions(o LookupOptions) error {
	switch o.Encoding {
	case "hex", "base64", "array":
	default:
		return fmt.Errorf("unknown encoding %q (want hex, base64, or array)", o.Encoding)
	}
	switch o.Loop {
	case "loop", "hold", "silence":
	default:
		return fmt.Errorf("unknown loop mode %q (want loop, hold, or silence)", o.Loop)
	}
	return nil
}

// renderLookup simulates the generated lookup expression, returning the
// bytes that will be output for t = 0, 1, 2, ... (length n).
func renderLookup(data []byte, loop string, center int, n int) []byte {
	out := make([]byte, n)
	for t := 0; t < n; t++ {
		switch loop {
		case "hold":
			idx := t
			if idx >= len(data) {
				idx = len(data) - 1
			}
			out[t] = data[idx]
		case "silence":
			if t < len(data) {
				out[t] = data[t]
			} else {
				out[t] = byte(center)
			}
		default: // loop
			out[t] = data[t%len(data)]
		}
	}
	return out
}

// generateLookupCode emits a pure bytebeat expression that plays `data`
// byte-per-sample and loops, holds, or goes silent at the end.
func generateLookupCode(data []byte, opts LookupOptions) string {
	n := len(data)
	switch opts.Encoding {
	case "array":
		nums := make([]string, n)
		for i, b := range data {
			nums[i] = strconv.Itoa(int(b))
		}
		arr := "[" + strings.Join(nums, ",") + "]"
		switch opts.Loop {
		case "hold":
			return fmt.Sprintf("%s[t<%d?t:%d]", arr, n, n-1)
		case "silence":
			return fmt.Sprintf("(t<%d?%s[t]:%d)", n, arr, opts.Center)
		default:
			return fmt.Sprintf("%s[t%%%d]", arr, n)
		}
	case "base64":
		b64 := base64.StdEncoding.EncodeToString(data)
		switch opts.Loop {
		case "hold":
			return fmt.Sprintf("atob(\"%s\").charCodeAt(t<%d?t:%d)", b64, n, n-1)
		case "silence":
			return fmt.Sprintf("(t<%d?atob(\"%s\").charCodeAt(t):%d)", n, b64, opts.Center)
		default:
			return fmt.Sprintf("atob(\"%s\").charCodeAt(t%%%d)", b64, n)
		}
	default: // hex
		h := hex.EncodeToString(data)
		switch opts.Loop {
		case "hold":
			return fmt.Sprintf("parseInt(\"%s\".slice((t<%d?t:%d)*2,(t<%d?t:%d)*2+2),16)", h, n, n-1, n, n-1)
		case "silence":
			return fmt.Sprintf("(t<%d?parseInt(\"%s\".slice(t*2,t*2+2),16):%d)", n, h, opts.Center)
		default:
			return fmt.Sprintf("parseInt(\"%s\".slice((t%%%d)*2,(t%%%d)*2+2),16)", h, n, n)
		}
	}
}

// bytebeatFile wraps generated code with an explanatory header comment.
func bytebeatFile(inputPath, code string, sampleRate int, numSamples int, mode string) string {
	dur := float64(numSamples) / float64(sampleRate)
	return fmt.Sprintf(`// Generated by bytebeat-convert (Go) from %q
// Mode: %s | Sample rate: %d Hz | Samples: %d | Duration: %.2f s
// Paste the next line into a bytebeat player and set the player's
// sample rate to %d Hz. The audio loops when playback continues past the end.
%s
`, filepath.Base(inputPath), mode, sampleRate, numSamples, dur, sampleRate, code)
}

// htmlTemplate is a minimal playable page: it evaluates the bytebeat
// expression once per sample and plays the result with Web Audio.
