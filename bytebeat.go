// generateHTML builds a self-contained playable HTML page for `code`.
func generateHTML(title, code string, sampleRate, numSamples int) string {
	escaped := strings.ReplaceAll(code, `\`, `\\`)
	escaped = strings.ReplaceAll(escaped, `"`, `\"`)
	escaped = strings.ReplaceAll(escaped, "</script>", "<\\/script>")
	h := htmlTemplate
	h = strings.ReplaceAll(h, "__TITLE__", title)
	h = strings.ReplaceAll(h, "__RATE__", strconv.Itoa(sampleRate))
	h = strings.ReplaceAll(h, "__N__", strconv.Itoa(numSamples))
	h = strings.ReplaceAll(h, "__CODE__", escaped)
	return h
}
