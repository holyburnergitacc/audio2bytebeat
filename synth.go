package main

import (
	"fmt"
	"math"
	"sort"
	"strings"
)

// SynthData is the spectral (sine-wave) approximation of an audio signal:
// each frame is described by a few sinusoids instead of raw samples.
type SynthData struct {
	NumSamples int
	SampleRate int
	FrameSize  int
	Partials   int
	Freqs      [][]float64 // [frame][partial], Hz (parabolically interpolated)
	Amps       [][]float64 // [frame][partial], linear amplitude (~0..1)
	Phases     [][]float64 // [frame][partial], FFT bin phase at frame start
	Gains      []float64   // [frame], sum of amps scaled so max == 1
}

// analyzeSynth runs an FFT per frame and keeps the strongest spectral peaks,
// refining each peak's frequency by parabolic interpolation and keeping its
// phase so frames can be resynthesized without phase drift.
func analyzeSynth(mono []float64, sampleRate, frameSize, partials int) *SynthData {
	numFrames := (len(mono) + frameSize - 1) / frameSize
	if numFrames < 1 {
		numFrames = 1
	}
	sd := &SynthData{
		NumSamples: len(mono),
		SampleRate: sampleRate,
		FrameSize:  frameSize,
		Partials:   partials,
		Freqs:      make([][]float64, numFrames),
		Amps:       make([][]float64, numFrames),
		Phases:     make([][]float64, numFrames),
		Gains:      make([]float64, numFrames),
	}
	frame := make([]float64, frameSize)
	maxGain := 0.0
	for f := 0; f < numFrames; f++ {
		for i := range frame {
			frame[i] = 0
		}
		copy(frame, mono[f*frameSize:minInt((f+1)*frameSize, len(mono))])
		mags, phases := fftSpectrum(frame)

		type peak struct {
			bin   int
			mag   float64
			freq  float64
			phase float64
		}
		var peaks []peak
		for b := 1; b < len(mags)-1; b++ {
			if mags[b] > mags[b-1] && mags[b] >= mags[b+1] && mags[b] > 0 {
				// Parabolic interpolation for sub-bin frequency accuracy.
				alpha, beta, gamma := mags[b-1], mags[b], mags[b+1]
				denom := alpha - 2*beta + gamma
				p := 0.0
				if denom != 0 {
					p = 0.5 * (alpha - gamma) / denom
					if p > 1 {
						p = 1
					}
					if p < -1 {
						p = -1
					}
				}
				freq := (float64(b) + p) * float64(sampleRate) / float64(frameSize)
				// The Hann window is centred at (N-1)/2, so the measured
				// bin phase is the sinusoid phase at the window centre.
				// Shift it back to the frame start (n=0) for resynthesis.
				phase := phases[b] - 2*math.Pi*freq*float64(frameSize-1)/2/float64(sampleRate)
				peaks = append(peaks, peak{
					bin:   b,
					mag:   mags[b],
					freq:  freq,
					phase: phase,
				})
			}
		}
		sort.Slice(peaks, func(i, j int) bool { return peaks[i].mag > peaks[j].mag })
		if len(peaks) > partials {
			peaks = peaks[:partials]
		}
		sort.Slice(peaks, func(i, j int) bool { return peaks[i].bin < peaks[j].bin })

		freqs := make([]float64, partials)
		amps := make([]float64, partials)
		ph := make([]float64, partials)
		sum := 0.0
		for i, pk := range peaks {
			freqs[i] = pk.freq
			ph[i] = pk.phase
			// Hann window: sine amplitude ~= 4*mag/N.
			amp := 4 * pk.mag / float64(frameSize)
			if amp > 1 {
				amp = 1
			}
			amps[i] = amp
			sum += amp
		}
		sd.Freqs[f] = freqs
		sd.Amps[f] = amps
		sd.Phases[f] = ph
		sd.Gains[f] = sum
		if sum > maxGain {
			maxGain = sum
		}
	}
	if maxGain > 0 {
		for f := range sd.Gains {
			sd.Gains[f] /= maxGain
		}
	}
	return sd
}

// normAmp returns per-frame amps normalized so each frame's amps sum to the
// frame gain (preserving dynamics while keeping output bounded).
func (sd *SynthData) normAmp(frame, p int) float64 {
	sum := 0.0
	for _, a := range sd.Amps[frame] {
		sum += a
	}
	if sum <= 0 {
		return 0
	}
	return sd.Amps[frame][p] / sum
}

// renderSynth evaluates the generated bytebeat expression in Go, producing
// the float samples. The result mirrors generateSynthCode exactly.
// Each partial restarts at its frame-local sample (t % frameSize) with the
// FFT phase measured at that frame's start, so phase never drifts.
func renderSynth(sd *SynthData, numSamples int) []float64 {
	out := make([]float64, numSamples)
	numFrames := len(sd.Freqs)
	for t := 0; t < numSamples; t++ {
		f := (t / sd.FrameSize) % numFrames
		// Offset inside the displayed frame; wraps consistently when
		// playback loops past the end (f wraps, local stays in range).
		local := t % sd.FrameSize
		sum := 0.0
		for p := 0; p < sd.Partials; p++ {
			freq := sd.Freqs[f][p]
			if freq == 0 {
				continue
			}
			sum += sd.normAmp(f, p) * math.Cos(2*math.Pi*freq*float64(local)/float64(sd.SampleRate)+sd.Phases[f][p])
		}
		out[t] = sum * sd.Gains[f]
	}
	return out
}

// generateSynthCode emits a pure bytebeat expression: a sum of sinusoids
// whose frequencies, amplitudes, phases and gains are looked up per frame.
// Tables are bound with the comma operator so the file stays a single
// expression (usable in strict single-expression bytebeat players):
//
//	(f=[...],g=[...],a=[...],p=[...],128+127*g[...]*...)
func generateSynthCode(sd *SynthData, center int) string {
	numFrames := len(sd.Freqs)
	var freqs, amps, phases, gains []string
	for f := 0; f < numFrames; f++ {
		for p := 0; p < sd.Partials; p++ {
			freqs = append(freqs, fmt.Sprintf("%.1f", sd.Freqs[f][p]))
			amps = append(amps, fmt.Sprintf("%.4f", sd.normAmp(f, p)))
			phases = append(phases, fmt.Sprintf("%.4f", sd.Phases[f][p]))
		}
		gains = append(gains, fmt.Sprintf("%.4f", sd.Gains[f]))
	}
	frameIdx := fmt.Sprintf("((t/%d)|0)%%%d", sd.FrameSize, numFrames)
	local := fmt.Sprintf("(t%%%d)", sd.FrameSize)
	var terms []string
	for p := 0; p < sd.Partials; p++ {
		terms = append(terms, fmt.Sprintf(
			"a[%s*%d+%d]*cos(6.2832*f[%s*%d+%d]*%s/%d+p[%s*%d+%d])",
			frameIdx, sd.Partials, p, frameIdx, sd.Partials, p, local, sd.SampleRate, frameIdx, sd.Partials, p))
	}
	return fmt.Sprintf("(f=[%s],g=[%s],a=[%s],p=[%s],%d+127*g[%s]*(%s))",
		strings.Join(freqs, ","), strings.Join(gains, ","), strings.Join(amps, ","), strings.Join(phases, ","),
		center, frameIdx, strings.Join(terms, "+"))
}

func minInt(a, b int) int {
	if a < b {
		return a
	}
	return b
}
